export function searchFlights(query: string): Flight[] {
  if (!query || query.trim() === '') {
    return MOCK_FLIGHTS;
  }

  const cleanQuery = query.trim().toUpperCase().replace(/\s+/g, '');

  return MOCK_FLIGHTS.filter((flight) => {
    const flightNum = flight.flightNumber.toUpperCase().replace(/\s+/g, '');
    const airline = flight.airline.toUpperCase();
    const airlineCode = flight.airlineCode.toUpperCase();
    const depCity = flight.departure.location.city.toUpperCase();
    const arrCity = flight.arrival.location.city.toUpperCase();
    const depCode = flight.departure.location.airportCode.toUpperCase();
    const arrCode = flight.arrival.location.airportCode.toUpperCase();

    // Check exact or partial flight number match (e.g. "AA100", "100", "AA", "UA881")
    if (flightNum.includes(cleanQuery)) return true;
    
    // Check if user typed airline code or name or route
    if (airline.includes(cleanQuery)) return true;
    if (airlineCode.includes(cleanQuery)) return true;
    if (depCode.includes(cleanQuery) || arrCode.includes(cleanQuery)) return true;
    if (depCity.includes(cleanQuery) || arrCity.includes(cleanQuery)) return true;

    return false;
  });
}
